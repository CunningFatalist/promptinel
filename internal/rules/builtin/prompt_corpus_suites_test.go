func promptRuleSuites() []promptRuleSuite {
	suites := make([]promptRuleSuite, 0)
	suites = append(suites, unicodeAndMarkupSuites()...)
	suites = append(suites, commandAndExecutionSuites()...)
	suites = append(suites, networkAndExfiltrationSuites()...)
	suites = append(suites, templateAndTrustSuites()...)
	suites = append(suites, protocolAndSkillSuites()...)
	return suites
}

